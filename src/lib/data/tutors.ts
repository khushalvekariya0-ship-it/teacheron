function build(seed: Seed): Tutor {
  const metro = METRO_BY_SLUG[seed.metro];
  const reviews = REVIEWS.filter((r) => r.tutorId === seed.id && r.status === "published");
  const rating = reviews.length ? Math.round((reviews.reduce((s, r) => s + r.rating, 0) / reviews.length) * 10) / 10 : null;
  const { metro: _metro, rules, verification, ...rest } = seed;
  void _metro;
  return {
    ...rest,
    city: metro.city,
    state: metro.state,
    zip: metro.zip,
    lat: metro.lat,
    lng: metro.lng,
    timezone: metro.timezone,
    rules: { ...DEFAULT_RULES, ...rules },
    verification: { ...UNVERIFIED, ...verification },
    rating,
    reviewCount: reviews.length,
    exceptions: [],
  };
}

/** Example profiles used ONLY inside illustrative product mock-ups (How it works, sign-in preview). Never listed or searchable. */
export const EXAMPLE_TUTORS: Tutor[] = SEEDS.map(build);

/** Sample tutors (empty when the sample-data switch is off). */
export const TUTORS: Tutor[] = SAMPLE_DATA ? EXAMPLE_TUTORS : [];

/** An example profile for a mock-up, by slug (falls back to the first example). */
export function exampleTutor(slugOrId: string): Tutor {
  return EXAMPLE_TUTORS.find((t) => t.slug === slugOrId || t.id === slugOrId) ?? EXAMPLE_TUTORS[0];
}

export const TUTOR_BY_ID: Record<string, Tutor> = Object.fromEntries(TUTORS.map((t) => [t.id, t]));
export const TUTOR_BY_SLUG: Record<string, Tutor> = Object.fromEntries(TUTORS.map((t) => [t.slug, t]));

export function getTutor(idOrSlug: string): Tutor | undefined {
  return TUTOR_BY_ID[idOrSlug] ?? TUTOR_BY_SLUG[idOrSlug];
}

export function tutorName(t: Pick<Tutor, "firstName" | "lastName">): string {
  return `${t.firstName} ${t.lastName}`;
}

/** Public display name: first name + last initial, as shown on cards before contact. */
export function tutorShortName(t: Pick<Tutor, "firstName" | "lastName">): string {
  return `${t.firstName} ${t.lastName.charAt(0)}.`;
}

/** True only when identity has actually been verified. Badges must use this, never a hard-coded flag. */
export function isIdentityVerified(t: Pick<Tutor, "verification">): boolean {
  return t.verification.identity === "verified";
}

export function verifiedKinds(t: Pick<Tutor, "verification">): VerificationKind[] {
  return (Object.keys(t.verification) as VerificationKind[]).filter((k) => t.verification[k] === "verified");
}
